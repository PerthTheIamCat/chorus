//! The projector: render the app's one memory into the per-agent files
//! each CLI expects to find in a workspace — `CLAUDE.md`, `AGENTS.md`,
//! `GEMINI.md` — then notice when a human has edited one by hand.
//!
//! Chorus keeps a single source of memory. Before it calls any agent it
//! writes that memory out in the shape that agent reads on startup, marks
//! the file as generated, and records a content hash so the next projection
//! can tell "still ours" from "the user changed this".
//!
//! Pure string work — the caller owns the filesystem.

use crate::types::BlobId;
use serde::{Deserialize, Serialize};
use std::path::Path;

/// Which agent's convention we're rendering for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AgentFile {
    /// `CLAUDE.md` — Claude Code / Claude Agent SDK.
    Claude,
    /// `AGENTS.md` — Codex and the broader `AGENTS.md` convention.
    Codex,
    /// `GEMINI.md` — Gemini CLI.
    Gemini,
}

impl AgentFile {
    /// Is `path` one of the memory files Chorus writes itself? Those are our
    /// output, not the agent's work, and listing them as "edited" in a handoff
    /// brief credits the agent with a file it never touched.
    pub fn is_projected(path: &str) -> bool {
        let name = path.rsplit('/').next().unwrap_or(path);
        matches!(name, "CLAUDE.md" | "AGENTS.md" | "GEMINI.md")
            || crate::skills::is_projected(path)
    }

    pub fn filename(self) -> &'static str {
        match self {
            Self::Claude => "CLAUDE.md",
            Self::Codex => "AGENTS.md",
            Self::Gemini => "GEMINI.md",
        }
    }

    pub fn all() -> [AgentFile; 3] {
        [Self::Claude, Self::Codex, Self::Gemini]
    }
}

/// The sections that go into a projected file, in render order. Every field
/// is already model-facing text (bullets, short prose) — the projector only
/// frames them.
#[derive(Debug, Clone, Default)]
pub struct Projection {
    /// Project-scope prose: architecture, conventions, build/test commands.
    /// Typically the hand-written `.chorus/project.md`.
    pub project: String,
    /// Rendered durable facts (see `memory::render`), one bullet per line.
    pub facts: String,
    /// The live task state (goal / done / pending), or empty between tasks.
    pub task_state: String,
    /// The skill index from [`crate::skills::index`]. Rendered only for
    /// agents with no skill loader of their own — Claude gets the real
    /// `.claude/skills/` files instead, and duplicating them here would pay
    /// for the same content twice in the same prompt.
    pub skills: String,
}

const MARKER: &str = "<!-- chorus:generated";
const CLOSE: &str = "-->";

/// What we found when re-reading a file we previously generated.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Drift {
    /// No such file — safe to write.
    Missing,
    /// Present, carries our marker, and the body still hashes to what the
    /// marker claims. Safe to overwrite.
    Untouched,
    /// Present but has no `chorus:generated` marker — a hand-written file we
    /// must not clobber.
    Foreign,
    /// Present, carries our marker, but the body no longer matches the
    /// recorded hash: a human edited it. Caller decides whether to keep
    /// their version, re-merge, or warn.
    Edited,
}

/// Render `p` for `target`, with the generated-marker header carrying a hash
/// of the body so [`drift`] can classify it later.
pub fn render(target: AgentFile, p: &Projection) -> String {
    let body = body(target, p);
    let hash = BlobId::of(body.as_bytes());
    format!(
        "{MARKER} {hash} — regenerated by Chorus before each agent turn; edits here are \
         detected, not silently kept {CLOSE}\n\n{body}\n"
    )
}

/// The body under the header — the part the hash covers.
fn body(target: AgentFile, p: &Projection) -> String {
    let mut s = String::new();
    s.push_str(&format!("# {} — projected memory\n", target.filename()));

    if !p.project.trim().is_empty() {
        s.push_str("\n## Project\n\n");
        s.push_str(p.project.trim());
        s.push('\n');
    }
    if !p.facts.trim().is_empty() {
        s.push_str("\n## Memory\n\n");
        s.push_str(p.facts.trim());
        s.push('\n');
    }
    if target != AgentFile::Claude && !p.skills.trim().is_empty() {
        s.push_str("\n## Skills\n\n");
        s.push_str(p.skills.trim());
        s.push('\n');
    }
    if !p.task_state.trim().is_empty() {
        s.push_str("\n## Current task\n\n");
        s.push_str(p.task_state.trim());
        s.push('\n');
    }
    s.trim_end().to_string()
}

/// Wrap already-written content in the generated marker, unchanged.
///
/// [`render`] frames a [`Projection`] into sections; a skill file is already
/// the exact text the agent must read, so framing it would corrupt it — its
/// own frontmatter has to stay the first line for Claude's loader to parse it.
/// What it still needs is the marker, so the next projection can tell our copy
/// from one the user edited. The marker goes in an HTML comment *after* the
/// frontmatter block for that reason.
pub fn render_raw(content: &str) -> String {
    let body = content.trim_end();
    let hash = BlobId::of(body.as_bytes());
    let note = format!(
        "\n\n{MARKER} {hash} — copied by Chorus from .chorus/skills; edit it there, not here {CLOSE}\n"
    );
    format!("{body}{note}")
}

/// [`drift`] for files written by [`render_raw`], where the marker trails the
/// content instead of leading it.
///
/// The two cannot share one function: `drift` finds the marker by
/// `strip_prefix`, so a skill file — whose first line must be its own
/// frontmatter — would read as `Foreign` forever and never be refreshed. That
/// is a silent failure mode (skills simply stop updating), which is why it
/// gets its own function and its own test rather than a flag.
pub fn drift_raw(contents: Option<&str>) -> Drift {
    let Some(text) = contents else {
        return Drift::Missing;
    };
    let Some(at) = text.rfind(MARKER) else {
        return Drift::Foreign;
    };
    let after = &text[at + MARKER.len()..];
    let Some(close_at) = after.find(CLOSE) else {
        return Drift::Foreign;
    };
    let claimed: Option<String> = after[..close_at]
        .split_whitespace()
        .find(|t| t.starts_with("b3:"))
        .map(str::to_string);
    let Some(claimed) = claimed else {
        return Drift::Edited;
    };
    let body = text[..at].trim_end();
    if BlobId::of(body.as_bytes()).to_string() == claimed {
        Drift::Untouched
    } else {
        Drift::Edited
    }
}

/// Classify a file's current contents relative to what we would generate.
/// Pass `None` when the file does not exist.
pub fn drift(contents: Option<&str>) -> Drift {
    let Some(text) = contents else {
        return Drift::Missing;
    };
    let Some(rest) = text.strip_prefix(MARKER) else {
        return Drift::Foreign;
    };
    let Some(close_at) = rest.find(CLOSE) else {
        return Drift::Foreign;
    };
    let header = &rest[..close_at];
    let claimed = header
        .split_whitespace()
        .find_map(|t| t.strip_prefix("b3:").map(|_| t.to_string()));
    let Some(claimed) = claimed else {
        return Drift::Edited;
    };

    // Body is everything after the header's closing `-->`, with the single
    // blank line `render` inserts trimmed back off each end.
    let body = rest[close_at + CLOSE.len()..].trim_matches(['\n', ' ']);
    let actual = BlobId::of(body.as_bytes());
    if actual.as_str() == claimed {
        Drift::Untouched
    } else {
        Drift::Edited
    }
}

/// A loaded project rule or instruction document.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ProjectRule {
    /// Relative or logical source path, e.g. `.chorus/rules/style.md`, `AGENTS.md`, `CLAUDE.md`.
    pub source: String,
    /// Content of the rule document.
    pub content: String,
}

impl ProjectRule {
    pub fn new(source: impl Into<String>, content: impl Into<String>) -> Self {
        Self {
            source: source.into(),
            content: content.into(),
        }
    }
}

/// Auto-load project instructions from `.chorus/rules/*.md`, `AGENTS.md`, and `CLAUDE.md`.
///
/// Discovers project rules from:
/// 1. `.chorus/rules/*.md` files, sorted deterministically by filename.
/// 2. `AGENTS.md` in the workspace root, if hand-written or edited (not generated by Chorus).
/// 3. `CLAUDE.md` in the workspace root, if hand-written or edited (not generated by Chorus),
///    deduplicating if its content is identical to an already loaded rule.
pub fn load_project_rules(workspace_root: &Path) -> Vec<ProjectRule> {
    let mut rules = Vec::new();

    // 1. .chorus/rules/*.md
    let rules_dir = workspace_root.join(".chorus").join("rules");
    if rules_dir.is_dir() {
        if let Ok(entries) = std::fs::read_dir(&rules_dir) {
            let mut paths = Vec::new();
            for entry in entries.flatten() {
                let p = entry.path();
                if p.is_file()
                    && p.extension()
                        .and_then(|e| e.to_str())
                        .map(|e| e.eq_ignore_ascii_case("md"))
                        .unwrap_or(false)
                {
                    paths.push(p);
                }
            }
            paths.sort();

            for path in paths {
                if let Ok(content) = std::fs::read_to_string(&path) {
                    if !content.trim().is_empty() {
                        let filename = path
                            .file_name()
                            .and_then(|n| n.to_str())
                            .unwrap_or("rule.md");
                        rules.push(ProjectRule::new(
                            format!(".chorus/rules/{filename}"),
                            content,
                        ));
                    }
                }
            }
        }
    }

    // 2. AGENTS.md
    let agents_path = workspace_root.join("AGENTS.md");
    if agents_path.is_file() {
        if let Ok(content) = std::fs::read_to_string(&agents_path) {
            // Only include if not purely untouched generated memory
            if drift(Some(&content)) != Drift::Untouched && !content.trim().is_empty() {
                rules.push(ProjectRule::new("AGENTS.md", content));
            }
        }
    }

    // 3. CLAUDE.md
    let claude_path = workspace_root.join("CLAUDE.md");
    if claude_path.is_file() {
        if let Ok(content) = std::fs::read_to_string(&claude_path) {
            if drift(Some(&content)) != Drift::Untouched && !content.trim().is_empty() {
                // Deduplicate identical content to avoid prompt token waste
                let is_dup = rules
                    .iter()
                    .any(|r| r.content.trim() == content.trim());
                if !is_dup {
                    rules.push(ProjectRule::new("CLAUDE.md", content));
                }
            }
        }
    }

    rules
}

/// Assembles loaded project rules into a model-facing instructions section.
pub fn assemble_rules(rules: &[ProjectRule]) -> String {
    if rules.is_empty() {
        return String::new();
    }

    let mut out = String::new();
    out.push_str("# Project Rules & Instructions\n\n");
    out.push_str(
        "The following project instructions and rules have been loaded from repository configuration:\n\n",
    );

    for (i, rule) in rules.iter().enumerate() {
        if i > 0 {
            out.push_str("\n\n");
        }
        out.push_str(&format!("## Rule: {}\n\n", rule.source));
        out.push_str(rule.content.trim());
    }

    out
}

/// Project rules into an agent system prompt.
/// Combines `base_system_prompt` and the assembled project rules.
pub fn project_rules_into_system_prompt(
    base_system_prompt: &str,
    rules: &[ProjectRule],
) -> String {
    let assembled = assemble_rules(rules);
    if assembled.is_empty() {
        return base_system_prompt.to_string();
    }

    let base = base_system_prompt.trim();
    if base.is_empty() {
        assembled
    } else {
        format!("{base}\n\n{assembled}")
    }
}

/// Project rules into an agent system prompt customized across bridges.
pub fn project_system_prompt_for_bridge(
    target: AgentFile,
    base_system_prompt: &str,
    rules: &[ProjectRule],
) -> String {
    let base = base_system_prompt.trim();
    let header = format!("<!-- Target Agent Bridge: {} -->", target.filename());
    let with_header = if base.is_empty() {
        header
    } else {
        format!("{header}\n{base}")
    };
    project_rules_into_system_prompt(&with_header, rules)
}

/// Convenience helper to load rules from workspace and project them into the system prompt.
pub fn assemble_workspace_rules(workspace_root: &Path, base_system_prompt: &str) -> String {
    let rules = load_project_rules(workspace_root);
    project_rules_into_system_prompt(base_system_prompt, &rules)
}

