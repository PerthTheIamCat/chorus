#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_and_unique() {
        for table in [FILE_NAMES, EXTENSIONS] {
            assert!(table.windows(2).all(|w| w[0].0 < w[1].0));
        }
    }

    #[test]
    fn common_extensions() {
        for (file, icon) in [
            ("main.rs", "rust"),
            ("notes.md", "markdown"),
            ("App.swift", "swift"),
            ("index.ts", "typescript"),
            ("data.json", "json"),
            ("config.toml", "toml"),
        ] {
            assert_eq!(icon_for(file), Some(icon), "{file}");
        }
    }

    #[test]
    fn file_name_beats_extension() {
        assert_eq!(icon_for("Cargo.toml"), Some("cargo"));
        assert_eq!(icon_for("Cargo.lock"), Some("cargo-lock"));
        assert_eq!(icon_for("package-lock.json"), Some("npm-lock"));
        assert_eq!(icon_for("README.md"), Some("readme"));
        assert_eq!(icon_for("rustfmt.toml"), Some("rust-config"));
    }

    #[test]
    fn extensionless_names() {
        assert_eq!(icon_for("Dockerfile"), Some("docker"));
        assert_eq!(icon_for("LICENSE"), Some("license"));
        assert_eq!(icon_for("README"), Some("readme"));
    }

    #[test]
    fn case_insensitive() {
        assert_eq!(icon_for("MAIN.RS"), Some("rust"));
        assert_eq!(icon_for("dockerfile"), Some("docker"));
        assert_eq!(icon_for("cargo.TOML"), Some("cargo"));
    }

    #[test]
    fn longest_extension_wins() {
        assert_eq!(icon_for("lib.d.ts"), Some("typescript-def"));
        assert_eq!(icon_for("foo.tar.ts"), Some("typescript"));
    }

    #[test]
    fn explicit_diff_and_lock() {
        assert_eq!(icon_for("change.diff"), Some("diff"));
        assert_eq!(icon_for("flake.lock"), Some("lock"));
        assert_eq!(icon_for("composer.lock"), Some("json"));
    }

    #[test]
    fn unknown_falls_back() {
        assert_eq!(icon_for("mystery.qqq"), None);
        assert_eq!(icon_for("Notes"), None);
        assert_eq!(icon_for("trailing."), None);
    }
}
