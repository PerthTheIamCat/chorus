//! File-type icon keys for the workspace tree.
//!
//! Shells map a key to a bundled glyph (`fi-<flavour>-<key>.svg` on macOS)
//! and fall back to their own generic icon on `None`. The lookup rules live
//! here so every shell resolves files the same way.
//!
//! Precedence follows VS Code's icon-theme contract: exact file name, then the
//! longest dotted extension (`lib.d.ts` tries `d.ts` before `ts`), all
//! case-insensitive.
//!
//! Tables come from Catppuccin Icons v1.26.0 (`src/defaults/fileIcons.ts`,
//! commit b6915da, MIT), cut down to the icons the macOS app bundles.
//! Parent-folder entries (`workflows/yml`) are dropped. `diff` is mapped only
//! through `languageIds` upstream and `lock` has no mapping at all, so both
//! get explicit extensions here.

/// Icon key for a file name, or `None` when the shell should use its fallback.
pub fn icon_for(file_name: &str) -> Option<&'static str> {
    let name = file_name.to_lowercase();
    if let Some(icon) = lookup(FILE_NAMES, &name) {
        return Some(icon);
    }
    // Leftmost dot first = longest extension first.
    name.match_indices('.')
        .find_map(|(i, _)| lookup(EXTENSIONS, &name[i + 1..]))
}

fn lookup(table: &'static [(&'static str, &'static str)], key: &str) -> Option<&'static str> {
    table
        .binary_search_by(|(k, _)| (*k).cmp(key))
        .ok()
        .map(|i| table[i].1)
}

